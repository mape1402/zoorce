namespace Zoorce.Web.UI.Navigation.Wizard;

/// <summary>Defines the amount of spacing around a wizard region.</summary>
public enum ZoorceWizardSpacing
{
    /// <summary>Uses the standard standalone wizard spacing.</summary>
    Standard,

    /// <summary>Uses compact spacing for contained workflows.</summary>
    Compact,

    /// <summary>Leaves spacing to the surrounding composition.</summary>
    None
}
