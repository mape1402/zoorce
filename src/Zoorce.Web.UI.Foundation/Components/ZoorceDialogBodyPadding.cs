namespace Zoorce.Web.UI.Foundation.Components;

/// <summary>Defines the amount of space around a dialog body slot.</summary>
public enum ZoorceDialogBodyPadding
{
    /// <summary>Uses the standard dialog body padding.</summary>
    Default,

    /// <summary>Uses compact padding for dense or contained content.</summary>
    Compact,

    /// <summary>Leaves body spacing entirely to the supplied content.</summary>
    None
}
