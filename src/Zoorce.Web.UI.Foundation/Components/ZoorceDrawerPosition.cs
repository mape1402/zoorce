namespace Zoorce.Web.UI.Foundation.Components;

/// <summary>Defines the edge from which a drawer enters the viewport.</summary>
public enum ZoorceDrawerPosition
{
    /// <summary>Places the drawer on the logical leading edge.</summary>
    Start,
    /// <summary>Places the drawer on the logical trailing edge.</summary>
    End,
    /// <summary>Places the drawer along the top edge.</summary>
    Top,
    /// <summary>Places the drawer along the bottom edge.</summary>
    Bottom
}
