namespace Zoorce.Web.UI.Foundation.Components;

/// <summary>Defines the standard size of a drawer surface.</summary>
public enum ZoorceDrawerSize
{
    /// <summary>Uses a compact surface for short secondary tasks.</summary>
    Compact,
    /// <summary>Uses the default surface size.</summary>
    Default,
    /// <summary>Uses a wide surface for detailed forms or inspectors.</summary>
    Wide,
    /// <summary>Uses the available viewport size.</summary>
    Full
}
