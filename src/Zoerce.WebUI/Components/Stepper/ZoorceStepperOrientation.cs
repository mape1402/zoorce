namespace Zoerce.WebUI.Components.Stepper;

/// <summary>Defines the direction in which a stepper presents its steps.</summary>
public enum ZoorceStepperOrientation
{
    /// <summary>Lets the component select a direction from its own available width.</summary>
    Auto,

    /// <summary>Places steps from left to right.</summary>
    Horizontal,

    /// <summary>Places steps from top to bottom.</summary>
    Vertical
}
